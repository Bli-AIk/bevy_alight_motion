/// 允许通过 Query 轻松定位特定图层。
/// Allows easy lookup of specific layers via Query.
///
/// # Example
/// ```rust,ignore
/// fn find_button(query: Query<Entity, With<AmLayerName>>) {
///     for entity in query.iter().filter(|e| e.0 == "MagicButton") { ... }
/// }
