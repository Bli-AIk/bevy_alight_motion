/// 图层过滤器，用于控制哪些图层被实例化。
/// Layer filter for controlling which layers are instantiated.
#[derive(Debug, Clone, Default)]
pub enum LayerFilter {
    /// 不过滤，生成所有图层 (No filtering, spawn all layers)
    #[default]
    None,
    /// 只生成名称在列表中的图层 (Only spawn layers with names in the list)
    AllowList(Vec<String>),
    /// 不生成名称在列表中的图层 (Don't spawn layers with names in the list)
    BlockList(Vec<String>),
}

impl LayerFilter {
    /// 检查图层是否应该被生成。
    /// Check if a layer should be spawned.
    pub fn should_spawn(&self, layer_name: &str) -> bool {
        match self {
            LayerFilter::None => true,
            LayerFilter::AllowList(list) => list.iter().any(|name| name == layer_name),
            LayerFilter::BlockList(list) => !list.iter().any(|name| name == layer_name),
        }
    }
}

